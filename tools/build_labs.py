"""Validate visual lab JSON and generate offline browser data."""
import json, math
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def check(test,message):
    if not test: raise ValueError(message)
def txt(x): return isinstance(x,str) and bool(x.strip())
def num(x): return type(x) in (float,int) and math.isfinite(x) and x>=0
data={}
for p in sorted((root/'labs').glob('*.json')):
    d=json.loads(p.read_text(encoding='utf-8')); kind=d.get('type'); check(kind in ('scenario-comparison','power-bi-workflow'),f'{p.name}: unknown lab type')
    if kind=='scenario-comparison':
        check(txt(d.get('title')) and txt(d.get('description')),f'{p.name}: missing heading')
        scenarios=d.get('scenarios');check(isinstance(scenarios,list) and scenarios,f'{p.name}: scenarios required')
        check(len({s['id'] for s in scenarios})==len(scenarios),'duplicate scenario ID')
        for s in scenarios:
            check(all(txt(s.get(k)) for k in ('id','label','title','description')),'invalid scenario text')
            views=s['views'];check(views and len({v['id'] for v in views})==len(views) and s['defaultView'] in {v['id'] for v in views},'invalid views/default')
            for v in views:
                check(txt(v['id']) and txt(v['label']) and v['kind'] in ('table','bars'),'invalid view')
                rows=v['rows'];check(isinstance(rows,list) and rows,'rows required')
                if v['kind']=='table':check(all(isinstance(r,list) and len(r)==len(rows[0]) and all(isinstance(x,str) for x in r) for r in rows) and bool(rows[0]),'invalid table rows')
                else:
                    check(num(v['max']) and v['max']>0,'invalid chart scale')
                    for r in rows:
                        check(txt(r['name']) and txt(r['label']),'missing chart label')
                        bars=r.get('bars',[r]);check(bars and all(num(b['value']) and b['value']<=v['max'] and b.get('kind','') in ('','warn','alt') for b in bars),'invalid chart value/style')
                if 'callout' in v:check(all(txt(v['callout'][k]) for k in ('title','text')),'invalid callout')
    data[p.stem]=d
check(bool(data),'No labs found')
(root/'generated'/'lab-data.js').write_text('// Generated by tools/build_labs.py. Do not edit manually.\nconst LAB_DATA = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
print(f'Built {len(data)} visual labs')
