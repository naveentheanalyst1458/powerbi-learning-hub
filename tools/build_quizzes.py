"""Validate quiz source JSON and compile for offline viewing and GitHub Pages."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
quizzes = {}
for p in sorted((ROOT/'quizzes').glob('*.json')):
    d=json.loads(p.read_text(encoding='utf-8'))
    def check(condition, message):
        if not condition: raise ValueError(f'{p.name}: {message}')
    check(isinstance(d.get('title'),str) and bool(d['title'].strip()),'title required')
    check(isinstance(d.get('resultTitle'),str) and bool(d['resultTitle'].strip()),'resultTitle required')
    check(type(d.get('passPercent')) is int and 1<=d['passPercent']<=100,'passPercent must be 1–100')
    check(type(d.get('markCompleteOnPass')) is bool,'markCompleteOnPass must be boolean')
    check(d.get('scoreStorageKey') is None or isinstance(d['scoreStorageKey'],str) and bool(d['scoreStorageKey'].strip()),'invalid scoreStorageKey')
    check(isinstance(d.get('questions'),list) and bool(d['questions']),'at least one question required')
    for i,q in enumerate(d['questions'],1):
        check(isinstance(q,dict),f'Q{i}: object required')
        check(all(isinstance(q.get(k),str) and bool(q[k].strip()) for k in ('question','why')),f'Q{i}: question and explanation required')
        opts=q.get('options')
        check(isinstance(opts,list) and len(opts)>=2 and all(isinstance(o,str) and bool(o.strip()) for o in opts),f'Q{i}: at least two options required')
        check(len(set(opts))==len(opts),f'Q{i}: duplicate options')
        check(type(q.get('correct')) is int and 0<=q['correct']<len(opts),f'Q{i}: correct index out of range')
    quizzes[p.stem]=d
if not quizzes: raise ValueError('No quiz sources found')
out=ROOT/'generated'/'quiz-data.js'
out.write_text('// Generated by tools/build_quizzes.py. Do not edit manually.\nconst QUIZ_DATA = '+json.dumps(quizzes,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
print(f'Built {len(quizzes)} quizzes, {sum(len(d["questions"]) for d in quizzes.values())} questions')
