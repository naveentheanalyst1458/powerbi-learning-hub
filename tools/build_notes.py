"""Compile trusted, reviewed lesson Markdown into browser-ready JavaScript.
Run from any directory: python tools/build_notes.py (from repository root).
"""
import json
from pathlib import Path
import mistune

ROOT = Path(__file__).resolve().parents[1]
class LessonRenderer(mistune.HTMLRenderer):
    def heading(self, text, level, **attrs):
        # Match the approved lesson typography for Markdown section headings.
        return super().heading(text, min(level + 3, 6), **attrs)
    def list(self, text, ordered, **attrs):
        tag = "ol" if ordered else "ul"
        start = f' start="{int(attrs["start"])}"' if ordered and attrs.get("start") is not None else ""
        return f'<{tag} class="notes-list"{start}>\n{text}</{tag}>\n'

# Raw HTML supports existing styled business tables and callouts. Only compile
# author-controlled, reviewed Markdown; never feed untrusted student input here.
renderer = LessonRenderer(escape=False)
markdown = mistune.create_markdown(renderer=renderer, plugins=["table"])
notes = {p.stem: markdown(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "content").glob("*.md"))}
output = ROOT / "generated" / "lesson-notes.js"
output.parent.mkdir(exist_ok=True)
output.write_text("// Generated by tools/build_notes.py. Do not edit manually.\nconst LESSON_NOTES = " + json.dumps(notes, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
print(f"Built {len(notes)} lesson(s): {', '.join(notes)}")
