"""Validate student resource configuration and compile browser-ready data."""
import json
from pathlib import Path
from urllib.parse import urlparse
ROOT = Path(__file__).resolve().parents[1]
resources = {}
for p in sorted((ROOT / 'resources').glob('*.json')):
    rows = json.loads(p.read_text(encoding='utf-8'))
    if not isinstance(rows, list):
        raise ValueError(f'{p.name}: expected an array')
    for i, row in enumerate(rows, 1):
        if not isinstance(row, dict) or not all(isinstance(row.get(k), str) and row[k].strip() for k in ('title','filename','description','type','details','url')):
            raise ValueError(f'{p.name}: resource {i} has missing fields')
        u = urlparse(row['url'])
        if u.scheme != 'https' or u.netloc not in ('drive.google.com', 'docs.google.com'):
            raise ValueError(f'{p.name}: resource {i} must use an HTTPS Google Drive link')
    resources[p.stem] = rows
(ROOT / 'generated' / 'resource-data.js').write_text('// Generated by tools/build_resources.py. Do not edit manually.\nconst RESOURCE_DATA = '+json.dumps(resources, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print(f'Built resources for {len(resources)} topics; {sum(map(len, resources.values()))} files')
